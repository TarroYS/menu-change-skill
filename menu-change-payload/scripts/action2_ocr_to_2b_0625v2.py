def _load_dish_codes_from_workbook(path: str) -> Dict[str, Dict[str, str]]:
    """Loads dish codes directly from the 'dish_code' tab of Excel 2a.
    Returns dict: {section_lower: {code_lower: sys_name}}"""
    codes = defaultdict(dict)

    try:
        wb = load_workbook(path, read_only=True)
        target_sheet = None
        for name in ['dish_code', 'Dish Code', 'Codes', 'codes']:
            if name in wb.sheetnames:
                target_sheet = name
                break

        if not target_sheet:
            wb.close()
            return codes

        ws = wb[target_sheet]
        rows = list(ws.iter_rows(values_only=True))
        if len(rows) < 2:
            wb.close()
            return codes

        headers = [str(h).strip() if h else '' for h in rows[0]]
        if 'Dish Group' not in headers or 'Dish Name:Primary' not in headers:
            wb.close()
            return codes

        group_col = headers.index('Dish Group')
        name_col = headers.index('Dish Name:Primary')

        variant_cols = [i for i, h in enumerate(headers) if h and h not in ['Dish Group', 'Dish Name:Primary', 'Dish Name:Secondary']]

        for row in rows[1:]:
            group = str(row[group_col]).strip().lower() if len(row) > group_col and row[group_col] else 'all'
            dish_name = str(row[name_col]).strip() if len(row) > name_col and row[name_col] else ''

            if not dish_name: continue

            for ci in variant_cols:
                if ci < len(row) and row[ci]:
                    code_val = str(row[ci]).strip().lower()
                    if code_val and code_val not in ('none', 'null', 'nan'):
                        if code_val.endswith('.0'): code_val = code_val[:-2]
                        codes[group][code_val] = dish_name

        wb.close()
    except Exception as e:
        print(f"  WARNING: Could not natively load dish codes from {path}: {e}")

    return codes


def _check_code_match(code: str, section: str, code_index: dict) -> Optional[str]:
    """Bouncer logic: Validates if an OCR code securely matches a system item via Section Neighborhood."""
    if not code or not code_index: return None
    c_lower = code.lower()
    s_lower = section.lower()
    
    # 1. Check exact neighborhood section
    if s_lower in code_index and c_lower in code_index[s_lower]:
        return code_index[s_lower][c_lower]
        
    # 2. Check global 'all' bucket if CSV didn't provide sections
    if 'all' in code_index and c_lower in code_index['all']:
        return code_index['all'][c_lower]
        
    # 3. Global Uniqueness Fallback
    matches = []
    for sec, items in code_index.items():
        if c_lower in items:
            matches.append(items[c_lower])
    if len(matches) == 1:
        return matches[0]
        
    return None


