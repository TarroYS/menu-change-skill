    def _try_with_section_prefix(menu_name: str, section_name: str) -> Optional[Tuple[str, str]]:
        clean = menu_name.strip().lower()

        # §2.5 — suffix-section safety net (runs before the bare-protein gate).
        sec_key = section_name.strip().lower()
        suffix_words = SUFFIX_SECTIONS.get(sec_key)
        if suffix_words and 1 <= len(clean.split()) <= 3:
            for sw in suffix_words:
                # "House Special" → "House Yat" (system drops "Special" for Yat).
                name_for_suffix = menu_name.strip()
                if sw == 'Yat' and clean in ('house special', 'house'):
                    name_for_suffix = 'House'
                cand = f'{name_for_suffix} {sw}'
                match = resolve_name(cand, sys_names, equiv)
                if match:
                    return (match[0], 'section_suffix')

        if clean not in BARE_PROTEINS:
            return None
        sec = section_name.strip()
        if not sec or sec.lower() in ('side orders', 'appetizers', 'soups', 'drinks',
                                       'lunch specials', 'combinations', 'catering party trays'):
            return None

        candidate1 = f'{sec} with {menu_name.strip()}'
        match = resolve_name(candidate1, sys_names, equiv)
        if match: return match

        candidate2 = f'{sec} {menu_name.strip()}'
        match = resolve_name(candidate2, sys_names, equiv)
        if match: return match

        candidate3 = f'{menu_name.strip()} {sec}'
        match = resolve_name(candidate3, sys_names, equiv)
        if match: return match

        resolved = _resolve_section(sec).lower()

        # §2.7 — when the section aliases to a multi-word system suffix
        # (e.g. "Stir Fried Udon" → "Stir Fry Udon Noodle"), append the
        # resolved suffix: "Chicken" → "Chicken Stir Fry Udon Noodle".
        # (sec may already arrive pre-resolved from the section router; the
        # `resolved` value covers both cases.)
        if resolved and resolved != sec.strip().lower():
            candidate_suffix = f'{menu_name.strip()} {resolved}'
            match = resolve_name(candidate_suffix, sys_names, equiv)
            if match: return match

        # Irregular: the "Vegetable" item in an Udon-noodle section drops
        # "Udon" → "Vegetable Stir Fry Noodle". Fire whether the section was
        # passed raw or pre-resolved, so key off whichever form has "udon".
        suffix_src = resolved if 'udon' in resolved else sec.strip().lower()
        if clean in ('vegetable', 'vegetables') and 'udon' in suffix_src and 'noodle' in suffix_src:
            no_udon = re.sub(r'\budon\s*', '', suffix_src).strip()
            no_udon = re.sub(r'\s+', ' ', no_udon)
            candidate_veg = f'{menu_name.strip()} {no_udon}'.strip()
            match = resolve_name(candidate_veg, sys_names, equiv)
            if match: return match

        if resolved == 'healthy dishes' or sec.lower().startswith('diet'):
            for prefix in ['Steam', 'Steamed']:
                candidate4 = f'{prefix} {menu_name.strip()}'
                match = resolve_name(candidate4, sys_names, equiv)
                if match: return match
                candidate5 = f'{prefix} {menu_name.strip()} with Broccoli'
                match = resolve_name(candidate5, sys_names, equiv)
                if match: return match
                candidate6 = f'{prefix} {menu_name.strip()} with Mixed Vegetables'
                match = resolve_name(candidate6, sys_names, equiv)
                if match: return match
        return None

    def _process_item(raw_menu_name, prices, section_name, original_code=None):
        # Tier 1 Cleansing
        cleaned_name = _clean_ocr_noise(raw_menu_name)
        code, cleaned_name = _extract_prefix_code(cleaned_name)
        qty, cleaned_name = _extract_quantity(cleaned_name)
        
        active_code = original_code if original_code else code
        # the code proposed on the Dish Code tab: the OCR's code field, or a
        # printed prefix only when it is clearly a code (not a count)
        paper_code = original_code if original_code else _printed_code_of(raw_menu_name)

        remapped_prices = remap_ocr_prices(prices, variant_style)

        has_parens = '(' in cleaned_name
        is_cm_cs = _is_chow_mein_chop_suey(cleaned_name)
        has_comma_or = bool(',' in cleaned_name and re.search(r'\bor\b', cleaned_name, re.IGNORECASE))
        is_compound = is_cm_cs or has_comma_or or bool(re.search(r'\b or \b', cleaned_name, re.IGNORECASE)) or '/' in cleaned_name
        is_complex = has_parens or is_compound

        # Identity is resolved by NAME (the 10-step pipeline), not by printed
        # menu number. Code is consulted ONLY as a tie-breaker, after name
        # resolution fails (see the `if not any_matched` block below).
        if has_parens or has_comma_or:
            expanded = _expand_parenthetical(cleaned_name, remapped_prices)
            if len(expanded) > 1:
                for exp_name, exp_prices in expanded:
                    _process_single(exp_name, exp_prices, section_name, active_code, raw_menu_name,
                                    paper_code)
                return

        candidates = split_compound_item(cleaned_name) if is_compound else [cleaned_name]
        any_matched = False
        
        for cand in candidates:
            match = resolve_name(cand, sys_names, equiv)
            if match:
                sys_name, method = match
                match_log.append({'menu': cand, 'system': sys_name, 'method': method, 'original': raw_menu_name, 'code': active_code, 'paper_code': paper_code, 'clean_name': cleaned_name, 'code_slots': sorted(remapped_prices.keys())})
                _record(sys_name, remapped_prices, section_name, raw_menu_name)
                any_matched = True
            else:
                prefix_match = _try_with_section_prefix(cand, section_name)
                if prefix_match:
                    sys_name, method = prefix_match
                    match_log.append({'menu': cand, 'system': sys_name, 'method': f'section_prefix+{method}', 'original': raw_menu_name, 'code': active_code, 'paper_code': paper_code, 'clean_name': cleaned_name, 'code_slots': sorted(remapped_prices.keys())})
                    _record(sys_name, remapped_prices, section_name, raw_menu_name)
                    any_matched = True
                    
        if not any_matched:
            # §2.6 — strict unique-substring auto-match before giving up.
            uniq = _unique_substring_match(cleaned_name, sys_names)
            if uniq:
                match_log.append({'menu': cleaned_name, 'system': uniq, 'method': 'unique_substring', 'original': raw_menu_name, 'code': active_code, 'paper_code': paper_code, 'clean_name': cleaned_name, 'code_slots': sorted(remapped_prices.keys())})
                _record(uniq, remapped_prices, section_name, raw_menu_name)
                return
            # CODE TIE-BREAKER: name resolution
            # produced no candidate. Consult the code as a last resort, but ONLY
            # if it is plausible — an implausible code hit goes to P4, not silently
            # accepted. Identity stays name-first; code only breaks the tie.
            if not is_complex and active_code:
                sys_name_from_code = _check_code_match(active_code, section_name, code_index)
                if sys_name_from_code:
                    if _is_code_match_plausible(cleaned_name, sys_name_from_code):
                        match_log.append({'menu': cleaned_name, 'system': sys_name_from_code, 'method': 'code_tiebreaker', 'original': raw_menu_name, 'code': active_code, 'paper_code': paper_code, 'clean_name': cleaned_name, 'code_slots': sorted(remapped_prices.keys())})
                        _record(sys_name_from_code, remapped_prices, section_name, raw_menu_name)
                        return
                    else:
                        flagged_code_matches.append({
                            'section': section_name,
                            'paper_name': raw_menu_name,
                            'clean_name': cleaned_name,
                            'system_name': sys_name_from_code,
                            'code': active_code,
                            'prices': remapped_prices,
                        })
            unmatched.append({'section': section_name, 'name': raw_menu_name, 'clean_name': cleaned_name, 'code': active_code, 'prices': remapped_prices})

