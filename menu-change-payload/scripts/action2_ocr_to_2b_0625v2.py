def _unique_substring_match(name: str, sys_names: List[str]) -> Optional[str]:
    """§2.6 — strict unique-substring auto-match. Accept a system row ONLY if
    the normalized paper name appears as a whole-word substring of exactly ONE
    system name (e.g. paper "Bourbon Chicken" → system "Street Bourbon Chicken").
    Ambiguous (>1 match) or zero matches → None (stays P1 for specialist review).
    Requires >=2 words and >=8 chars to avoid matching generic short proteins."""
    clean = _normalize(name).lower().strip()
    if len(clean.split()) < 2 or len(clean) < 8:
        return None
    matches = []
    pattern = r'(^|\s)' + re.escape(clean) + r'($|\s)'
    for sn in sys_names:
        sn_norm = _normalize(sn).lower().strip()
        if clean == sn_norm:
            return sn
        if re.search(pattern, sn_norm):
            matches.append(sn)
    if len(matches) == 1:
        return matches[0]
    return None


def _suggest_match(name: str, sys_names: List[str], equiv: Dict) -> str:
    clean = _normalize(name).lower()
    no_fried = re.sub(r'^fried\s+', '', clean)
    sys_lower = {s.lower(): s for s in sys_names}
    sys_norm = {_normalize(s).lower(): s for s in sys_names}
    if no_fried != clean and no_fried in sys_norm:
        return f"Maybe: {sys_norm[no_fried]} (stripped 'Fried')"
    for sn in sys_names:
        sn_norm = _normalize(sn).lower()
        if len(clean) > 5 and clean in sn_norm:
            return f"Maybe: {sn} (substring)"
        if len(sn_norm) > 5 and sn_norm in clean:
            return f"Maybe: {sn} (substring)"
    return ''


