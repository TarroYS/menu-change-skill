def _normalize(name: str) -> str:
    if not name: return ""
    n = str(name).strip()
    n = re.sub(r'\s*\(\d+\)\s*$', '', n)
    n = re.sub(r'\s*\([^)]*\)\s*', ' ', n)
    n = n.replace("\u2019s ", " ").replace("'s ", " ")
    n = n.replace('&', 'and')
    n = re.sub(r'\bw\.\s*', 'with ', n)
    n = re.sub(r'\bw/\s*', 'with ', n)
    n = re.sub(r'\bveg\.', 'vegetable', n, flags=re.IGNORECASE)
    n = re.sub(r'\bvegs\.', 'vegetables', n, flags=re.IGNORECASE)
    n = re.sub(r'\bveg\b', 'vegetable', n, flags=re.IGNORECASE)
    n = re.sub(r'\bvegs\b', 'vegetables', n, flags=re.IGNORECASE)
    n = re.sub(r'\bchk\b', 'chicken', n, flags=re.IGNORECASE)
    n = re.sub(r'\bshr\b', 'shrimp', n, flags=re.IGNORECASE)
    n = re.sub(r'\bsp\.\b', 'special', n, flags=re.IGNORECASE)
    n = re.sub(r'\bhse\b', 'house', n, flags=re.IGNORECASE)
    n = re.sub(r'\bbar-?b-?q\b', 'barbecue', n, flags=re.IGNORECASE)
    n = re.sub(r'\bb\.?b\.?q\.?\b', 'barbecue', n, flags=re.IGNORECASE)
    n = re.sub(r'\bspareribs\b', 'spare ribs', n, flags=re.IGNORECASE)
    n = re.sub(r'\bspare rib\b(?!s)', 'spare ribs', n, flags=re.IGNORECASE)
    n = re.sub(r'\bsteamed\b', 'steam', n, flags=re.IGNORECASE)
    n = n.replace('-', ' ')
    n = re.sub(r"[^a-zA-Z0-9\s]", '', n)
    n = re.sub(r'\s+', ' ', n).strip()
    return n

def _strip_descriptors(name: str) -> str:
    n = name
    for suffix in [r'\s+with\s+white\s+sauce$', r'\s+with\s+brown\s+sauce$',
                   r'\s+with\s+onions?$', r'\s+with\s+onion$']:
        n = re.sub(suffix, '', n, flags=re.IGNORECASE)
    n = re.sub(r'\s+style\b', '', n, flags=re.IGNORECASE)
    return n.strip()

