"""
action2_ocr_to_2b_0625v2.py — OCR JSON + Excel 2a → Excel 2b (v5 - Cuisine-Agnostic)
===================================================================================

Standalone script. Dependencies: openpyxl only.
Works for any restaurant cuisine — variant columns are auto-discovered from the
Menu Preview header row (no hardcoded variant whitelist). Tested on Chinese-
American (No.1 Chinese, China One, Bei Jing, Jade Garden, Best Food In Town,
etc.) and sushi/Japanese (SeaPark Sushi).

Usage:
    python action2_ocr_to_2b_0625v2.py <menu_ocr.json> <excel_2a.xlsx> [--dict <wonders_dict.xlsx>] [--codes <dish_codes.csv>] [--output <output.xlsx>]

What it does:
    Produces Excel 2b that MIRRORS 2a's structure exactly.

    Includes Deterministic Code Matching:
      - Reads POS dish codes (CSV/Excel).
      - Checks for Section + Code match before attempting fuzzy text matching.
      - Uses "Bouncer Logic" to safely bypass codes on compound/split items.

    Includes Tier 1 OCR Cleansing:
      - Non-ASCII/Multilingual stripping
      - Text-Price Bleed correction (e.g. "Chic11.99" -> "Chic 11.99")
      - Prefix Code extraction (e.g. "L15. General Tso" -> "General Tso")
      - Quantity normalization (e.g. "Chicken Wings (4)" -> "Chicken Wings")
      - Global "Bubble Price" fallback inheritance

    Variant column handling:
      - Auto-discovers ALL variant columns from the Menu Preview header row.
      - Writes to any column the OCR JSON specifies, regardless of cuisine.
      - See `_detect_extra_variants()` for the rationale and history.
"""

