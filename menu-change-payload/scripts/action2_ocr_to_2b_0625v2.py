def _detect_extra_variants(headers: list) -> list:
    """
    Return the list of variant column headers to write to.

    Auto-discovers ALL columns in the price tab header row that aren't
    name/group columns. The Menu Preview's header row is the source of
    truth — if a column exists there, it's a valid variant write target.

    Why this isn't a hardcoded whitelist:
      Older versions of this function gated writes by a PRICE_VARIANTS
      whitelist plus a regex for "N Ounce" columns. That silently dropped
      writes to restaurant-specific variant columns — e.g., 'Roll' for
      sushi maki, 'Dinner' for bento boxes, 'Seapark' for restaurant-
      specific combo sets, 'Bowl' for poke bowls, 'Regular Roll' for
      party-tray roll bundles. Names matched fine, but the price write
      to the niche column was a no-op.
      The Menu Preview is generated by Action 1 from the Raw Gsheet and
      already contains every variant column the restaurant uses, so the
      correct behavior is: trust the headers, write everywhere they
      point.
    """
    variants = []
    seen = set()
    for h in headers:
        h = str(h).strip() if h else ''
        if not h:
            continue
        if h in NAME_COLUMNS:
            continue
        if h in seen:
            continue
        seen.add(h)
        variants.append(h)
    return variants


def _parse_price(val) -> Optional[float]:
    if val is None or str(val).strip() in ('', 'None', 'NULL'):
        return None
    s = str(val).strip().replace('$', '').replace(',', '')
    try:
        return float(s)
    except ValueError:
        return None

def _fmt(val) -> str:
    if val is None: return ''
    try: return f'${float(val):.2f}'
    except: return ''


