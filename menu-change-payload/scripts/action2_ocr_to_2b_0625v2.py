def _load_wonders_dict(path: str) -> Dict[str, Set[str]]:
    wb = load_workbook(path, read_only=True)
    target_sheet = None
    for name in ['Sheet1', 'sheet1', 'Dictionary', 'dictionary', 'Dict']:
        if name in wb.sheetnames:
            target_sheet = name
            break
    if target_sheet is None:
        target_sheet = wb.sheetnames[0]
    ws = wb[target_sheet]
    reverse = {}
    for row in ws.iter_rows(min_row=10, values_only=True):
        entity = row[0] if len(row) > 0 and row[0] else None
        name1 = row[1] if len(row) > 1 and row[1] else None
        name2 = row[2] if len(row) > 2 and row[2] else None
        if not entity or not name1: continue
        canonical = str(name1).strip()
        reverse[canonical.lower()] = canonical
        if name2 and str(name2).strip():
            for alias in str(name2).split(','):
                alias = alias.strip()
                if alias: reverse[alias.lower()] = canonical
    wb.close()
    equiv = {}
    for alias_lower, canonical in reverse.items():
        can_lower = canonical.lower()
        group = equiv.get(alias_lower, set()) | equiv.get(can_lower, set())
        group.add(alias_lower)
        group.add(can_lower)
        for member in group:
            equiv[member] = group
    return equiv

def _lookup(candidate: str, sys_lower: dict, sys_norm: dict,
            equiv: dict) -> Optional[Tuple[str, str]]:
    c = candidate.lower()
    cn = _normalize(candidate).lower()
    if c in sys_lower: return (sys_lower[c], 'direct')
    if cn in sys_norm: return (sys_norm[cn], 'normalized')
    group = equiv.get(c, set()) | equiv.get(cn, set())
    for member in group:
        if member in sys_lower: return (sys_lower[member], 'equiv_class')
        mn = _normalize(member).lower()
        if mn in sys_norm: return (sys_norm[mn], 'equiv_class')
    return None

def _phonetic_variants(text: str) -> List[str]:
    """§2.4 — for a normalized lowercase string, yield variants where each
    phonetic-alias spelling is swapped for its alternatives. One swap at a
    time (whole-word, regex-bounded) to keep the candidate set small."""
    variants = []
    seen = set()
    for group in PHONETIC_ALIASES:
        for src in group:
            if re.search(r'\b' + re.escape(src) + r'\b', text):
                for dst in group:
                    if dst == src:
                        continue
                    cand = re.sub(r'\b' + re.escape(src) + r'\b', dst, text)
                    if cand != text and cand not in seen:
                        seen.add(cand)
                        variants.append(cand)
    return variants

def resolve_name(menu_name: str, system_names: List[str],
                 equiv: Dict[str, Set[str]]) -> Optional[Tuple[str, str]]:
    if not menu_name: return None
    sys_lower = {s.lower(): s for s in system_names}
    sys_norm = {_normalize(s).lower(): s for s in system_names}

    result = _lookup(menu_name, sys_lower, sys_norm, equiv)
    if result: return result

    stripped = _strip_descriptors(_normalize(menu_name))
    if stripped.lower() != _normalize(menu_name).lower():
        result = _lookup(stripped, sys_lower, sys_norm, equiv)
        if result: return (result[0], 'stripped')

    test = _normalize(menu_name).lower()
    for pat, repl in PATTERN_SUBS:
        modified = re.sub(pat, repl, test, flags=re.IGNORECASE).strip()
        modified = re.sub(r'\s+', ' ', modified)
        if modified != test:
            result = _lookup(modified, sys_lower, sys_norm, equiv)
            if result: return (result[0], 'pattern')
            for word in modified.split():
                if word.endswith('s') and len(word) > 3:
                    singular = re.sub(r'\b' + re.escape(word) + r'\b', word[:-1], modified)
                    result = _lookup(singular, sys_lower, sys_norm, equiv)
                    if result: return (result[0], 'pattern+plural')
                elif not word.endswith('s') and len(word) > 3:
                    plural = re.sub(r'\b' + re.escape(word) + r'\b', word + 's', modified)
                    result = _lookup(plural, sys_lower, sys_norm, equiv)
                    if result: return (result[0], 'pattern+plural')

    words = _normalize(menu_name).lower().split()
    if 2 <= len(words) <= 5:
        flipped = ' '.join([words[1], words[0]] + words[2:])
        result = _lookup(flipped, sys_lower, sys_norm, equiv)
        if result: return (result[0], 'word_flip')
        flipped_stripped = _strip_descriptors(flipped)
        if flipped_stripped != flipped:
            result = _lookup(flipped_stripped, sys_lower, sys_norm, equiv)
            if result: return (result[0], 'word_flip+strip')

    test_with = _normalize(menu_name).lower()
    if ' with ' in test_with:
        parts = test_with.split(' with ', 1)
        if len(parts) == 2:
            flipped_with = parts[1].strip() + ' with ' + parts[0].strip()
            result = _lookup(flipped_with, sys_lower, sys_norm, equiv)
            if result: return (result[0], 'with_flip')
            left, right = parts[0].strip(), parts[1].strip()
            style_stripped = re.sub(r'\s*style\s*$', '', left, flags=re.IGNORECASE).strip()
            if style_stripped != left:
                combined = style_stripped + ' ' + right
                result = _lookup(combined, sys_lower, sys_norm, equiv)
                if result: return (result[0], 'style_flip')
                combined2 = right + ' ' + style_stripped
                result = _lookup(combined2, sys_lower, sys_norm, equiv)
                if result: return (result[0], 'style_flip')

    # §2.1 — "X and Y" (incl. paper "X & Y", already normalized to "and") with
    # no "with": try "Y with X", "X with Y", "Y X", "X Y". Handles paper
    # "Scallops & Beef" → system "Beef with Scallops",
    # "Fried Bean Curd w. Broccoli"-style reorders, etc.
    test_and = _normalize(menu_name).lower()
    if ' and ' in test_and and ' with ' not in test_and:
        a_parts = test_and.split(' and ')
        if len(a_parts) == 2:
            x, y = a_parts[0].strip(), a_parts[1].strip()
            if x and y and len(test_and.split()) <= 6:
                for cand, tag in [
                    (f'{y} with {x}', 'and_flip'),
                    (f'{x} with {y}', 'and_flip'),
                    (f'{y} {x}', 'and_reorder'),
                    (f'{x} {y}', 'and_reorder'),
                ]:
                    result = _lookup(cand, sys_lower, sys_norm, equiv)
                    if result: return (result[0], tag)

    # §2.2 — strip a trailing "Style" token, then try direct + reorderings.
    # Handles "Bean Curd Szechuan Style" → "Szechuan Bean Curd" (trailing
    # qualifier moved to front) and adjacent first-two-word flips.
    base = _normalize(menu_name).lower()
    destyled = re.sub(r'\s+style$', '', base).strip()
    if destyled != base and destyled:
        result = _lookup(destyled, sys_lower, sys_norm, equiv)
        if result: return (result[0], 'style_strip')
        dwords = destyled.split()
        if 2 <= len(dwords) <= 5:
            # trailing qualifier → front: "bean curd szechuan" → "szechuan bean curd"
            rotated = ' '.join([dwords[-1]] + dwords[:-1])
            result = _lookup(rotated, sys_lower, sys_norm, equiv)
            if result: return (result[0], 'style_strip+rotate')
            # adjacent first-two-word flip
            dflip = ' '.join([dwords[1], dwords[0]] + dwords[2:])
            result = _lookup(dflip, sys_lower, sys_norm, equiv)
            if result: return (result[0], 'style_strip+flip')

    # §2.4 — phonetic / spelling-drift swaps (Shu mai↔Shao Mai, Kung Po↔Pao,
    # Hunan↔Hu Nan, Szechuan↔Sichuan, Tso↔Tsos). Try each swapped variant.
    for variant in _phonetic_variants(_normalize(menu_name).lower()):
        result = _lookup(variant, sys_lower, sys_norm, equiv)
        if result: return (result[0], 'phonetic')

    test = _normalize(menu_name).lower()
    for word in test.split():
        if word.endswith('s') and len(word) > 3:
            singular = re.sub(r'\b' + re.escape(word) + r'\b', word[:-1], test)
            result = _lookup(singular, sys_lower, sys_norm, equiv)
            if result: return (result[0], 'plural_strip')
        elif not word.endswith('s') and len(word) > 3:
            plural = re.sub(r'\b' + re.escape(word) + r'\b', word + 's', test)
            result = _lookup(plural, sys_lower, sys_norm, equiv)
            if result: return (result[0], 'plural_add')

    return None

def _is_chow_mein_chop_suey(name: str) -> bool:
    n = name.lower()
    return ('chow mein' in n and 'chop suey' in n) or \
           ('chow mein' in n and '/' in n and 'suey' in n)

def split_chow_mein_chop_suey(name: str) -> List[str]:
    n = name.strip()
    cm_match = re.match(r'^(.+?)\s*chow\s+mein\s*/\s*chop\s+suey(.*)$', n, re.IGNORECASE)
    if cm_match:
        prefix = cm_match.group(1).strip()
        suffix = cm_match.group(2).strip()
        chow_mein_name = f"{prefix} Chow Mein{(' ' + suffix) if suffix else ''}"
        chop_suey_name = f"{prefix} Chop Suey{(' ' + suffix) if suffix else ''}"
        return [chow_mein_name, chop_suey_name]
    return [name]

def split_compound_item(name: str) -> List[str]:
    if _is_chow_mein_chop_suey(name):
        return split_chow_mein_chop_suey(name)

    clean = re.sub(r'\s*\([^)]*\)\s*', ' ', name).strip()
    clean = re.sub(r'\s+', ' ', clean)

    or_count = len(re.findall(r'\bor\b', clean, re.IGNORECASE))
    has_comma = ',' in clean

    if or_count >= 2 or (has_comma and or_count >= 1):
        with_match = re.match(r'^(.+?)\s+(?:with|w\.)\s+(.+)$', clean, re.IGNORECASE)
        if with_match:
            base = with_match.group(1).strip()
            protein_list = with_match.group(2).strip()
            proteins = re.split(r',\s*|\s+or\s+', protein_list)
            proteins = [p.strip() for p in proteins if p.strip()]
            if len(proteins) >= 2:
                return [f'{base} with {p}' for p in proteins]

        all_parts = re.split(r',\s*|\s+or\s+', clean)
        all_parts = [p.strip() for p in all_parts if p.strip()]
        if len(all_parts) >= 2:
            first_words = all_parts[0].split()
            last_words = all_parts[-1].split()
            mid_parts = all_parts[1:-1] if len(all_parts) > 2 else []
            mid_word_counts = [len(p.split()) for p in mid_parts] if mid_parts else []
            all_mid_single = all(c == 1 for c in mid_word_counts) if mid_word_counts else True

            if all_mid_single and len(last_words) >= 2 and len(first_words) == 1:
                last_protein = last_words[0]
                suffix = ' '.join(last_words[1:])
                proteins = [all_parts[0]] + all_parts[1:-1] + [last_protein]
                return [f'{p} {suffix}' for p in proteins]
            elif all_mid_single and len(first_words) >= 2 and len(last_words) == 1:
                prefix = ' '.join(first_words[:-1])
                first_protein = first_words[-1]
                proteins = [first_protein] + all_parts[1:]
                return [f'{prefix} {p}' for p in proteins]
            elif all_mid_single and len(first_words) >= 2 and len(last_words) >= 2:
                prefix = ' '.join(first_words[:-1])
                first_protein = first_words[-1]
                last_protein = last_words[0]
                suffix = ' '.join(last_words[1:])
                proteins = [first_protein] + all_parts[1:-1] + [last_protein]
                return [f'{prefix} {p} {suffix}' for p in proteins]

    if ' or ' in clean.lower():
        idx = clean.lower().index(' or ')
        left, right = clean[:idx].strip(), clean[idx+4:].strip()
    elif '/' in clean:
        parts = clean.split('/', 1)
        left, right = parts[0].strip(), parts[1].strip()
    else:
        return [name]

    rw = right.split()
    lw = left.split()

    # Dish-type suffix swap: "X Mei Fun or Ho Fun" → ["X Mei Fun", "X Ho Fun"]
    # When "or" separates two known multi-word dish types that share a protein prefix,
    # keep the prefix and swap the dish type suffix on each side.
    _DISH_TYPE_SUFFIXES = {
        'mei fun', 'ho fun', 'chow fun', 'lo mein', 'chow mein',
        'chop suey', 'egg foo young', 'fried rice', 'yat gaw mein',
    }
    left_lower = left.lower()
    right_lower = right.lower().strip()
    for dt_suffix in sorted(_DISH_TYPE_SUFFIXES, key=len, reverse=True):
        if left_lower.endswith(dt_suffix) and right_lower in _DISH_TYPE_SUFFIXES:
            prefix = left[:len(left) - len(dt_suffix)].strip()
            if prefix:
                return [left, f'{prefix} {right}']
            else:
                return [left, right]

    if len(rw) > 1 and len(lw) > 1:
        suffix = ' '.join(rw[1:])
        prefix = ' '.join(lw[:-1])
        left_ends_with_suffix = left.lower().endswith(suffix.lower())
        right_starts_with_prefix = right.lower().startswith(prefix.lower())

        if left_ends_with_suffix or right_starts_with_prefix:
            return [left, right]
        else:
            right_suffix = ' '.join(rw[1:]).lower()
            known_suffixes = {'soup', 'lo mein', 'fried rice', 'chow mein', 'chop suey',
                              'mei fun', 'chow fun', 'egg foo young', 'roll', 'rolls'}
            if right_suffix in known_suffixes and len(lw) >= 2:
                left_prefix = ' '.join(lw[:-1])
                return [left + ' ' + ' '.join(rw[1:]), left_prefix + ' ' + right]
            return [left, right]
    elif len(rw) > 1:
        with_idx = None
        for i, w in enumerate(rw):
            if w.lower() in ('with', 'w.', 'w/'):
                with_idx = i
                break
        if with_idx is not None and with_idx > 0:
            suffix = ' '.join(rw[with_idx:])
            return [left + ' ' + suffix, right]
        else:
            suffix = ' '.join(rw[1:])
            left_ends_with_suffix = left.lower().endswith(suffix.lower())
            if left_ends_with_suffix:
                return [left, right]
            return [left + ' ' + suffix, right]
    elif len(lw) > 1:
        prefix = ' '.join(lw[:-1])
        return [left, prefix + ' ' + right]
    return [left, right]


def map_prices_to_2a_row(row_2a_prices: Dict[str, Optional[float]],
                         ocr_prices: Dict[str, float]):
    """Map OCR (paper) prices onto the system row's variant columns.

    Returns (mapped, inferred, unplaced, src) where:
      - mapped:   {variant -> price} to write
      - inferred: list of {'paper_variant','target_variant','price'} for any
                  price whose paper variant column is blank in the system row
                  but exactly one other variant column is populated, so we
                  route it there instead of silently dropping it (§ column
                  inference / silent-G1 fix).
      - unplaced: list of {'paper_variant','price'} — printed prices for a size
                  the system dish does not have that could not be routed (it
                  has several other sizes, or none; a tray on a dish without a
                  tray price). Never written (G1), but never dropped silently
                  either: action3 asks about each (Questionnaire P-SIZE).
      - src:      {system variant -> [every paper variant whose price landed
                  there, in order]} — the last one is the price written; an
                  earlier one was overwritten (two printed prices for one size).
                  The printed dish codes of all of them belong to that size.
    """
    mapped = {}
    inferred = []
    unplaced = []
    src = defaultdict(list)
    has = {v for v, p in row_2a_prices.items() if p is not None}

    for var, price in ocr_prices.items():
        if var in TRAY_VARIANTS:
            # v4.3: tray prices are no longer discarded (old G9). Write to
            # the tray column only when the system row already has a tray
            # price (G1); never fall through to the re-routing below.
            if var in has:
                mapped[var] = price
                src[var].append(var)
            else:
                unplaced.append({'paper_variant': var, 'price': price})
            continue
        if var in has:
            mapped[var] = price
            src[var].append(var)
            continue
        placed = False
        if var == 'Order' and 'Order' not in has:
            if 'Large' in has and 'Small' not in has:
                mapped['Large'] = price
                src['Large'].append(var)
                placed = True
            elif 'Large' in has and 'Small' in has:
                old_sm = row_2a_prices.get('Small', 0) or 0
                old_lg = row_2a_prices.get('Large', 0) or 0
                if old_sm > 0 and old_lg > 0:
                    dist_sm = abs(price - old_sm)
                    dist_lg = abs(price - old_lg)
                    if dist_sm < dist_lg:
                        mapped['Small'] = price
                        src['Small'].append(var)
                    else:
                        mapped['Large'] = price
                        src['Large'].append(var)
                else:
                    mapped['Large'] = price
                    src['Large'].append(var)
                placed = True
        if not placed and len(has) == 1:
            # Name matched but the paper's variant column is blank in the
            # system row, and exactly one other variant column is populated.
            # Infer that column rather than silently skipping the update (G1).
            target = next(iter(has))
            if target not in mapped:
                mapped[target] = price
                src[target].append(var)
                inferred.append({
                    'paper_variant': var,
                    'target_variant': target,
                    'price': price,
                })
                placed = True
        if not placed:
            unplaced.append({'paper_variant': var, 'price': price})
    return mapped, inferred, unplaced, src

def detect_variant_style(p_headers: list, price_rows: list) -> str:
    from collections import Counter
    var_counts = Counter()
    total = 0
    for r in price_rows[1:]:
        name = str(r[1]).strip() if len(r) > 1 and r[1] else ''
        if not name:
            continue
        total += 1
        for v in ['Small', 'Large', 'Lunch']:
            ci = p_headers.index(v) if v in p_headers else -1
            if ci >= 0 and ci < len(r) and r[ci]:
                s = str(r[ci]).strip()
                if s.startswith('$') or (s.replace('.', '').replace(',', '').isdigit()):
                    var_counts[v] += 1
    has_small = var_counts['Small'] > 0
    has_lunch = var_counts['Lunch'] > 0
    if has_lunch and not has_small:
        return 'lunch_based'
    elif has_small and not has_lunch:
        return 'size_based'
    elif has_small and has_lunch:
        # Count items that have BOTH Small and Lunch prices — if significant,
        # the restaurant uses Pt/Qt sizing AND a separate Lunch column
        # independently (e.g., Best Food In Town R81001). Treat as size_based
        # so Small stays Small; Lunch Specials route via lunch_specials JSON key.
        small_idx = p_headers.index('Small') if 'Small' in p_headers else -1
        lunch_idx = p_headers.index('Lunch') if 'Lunch' in p_headers else -1
        both_count = 0
        if small_idx >= 0 and lunch_idx >= 0:
            for r in price_rows[1:]:
                if len(r) > 1 and r[1] and str(r[1]).strip():
                    has_s = small_idx < len(r) and r[small_idx] and str(r[small_idx]).strip().replace('$','').replace(',','').replace('.','').isdigit()
                    has_l = lunch_idx < len(r) and r[lunch_idx] and str(r[lunch_idx]).strip().replace('$','').replace(',','').replace('.','').isdigit()
                    if has_s and has_l:
                        both_count += 1
        if both_count >= 20:
            return 'size_based'
        return 'lunch_based' if var_counts['Lunch'] > var_counts['Small'] else 'size_based'
    else:
        return 'size_based'

def remap_ocr_prices(prices: Dict[str, float], variant_style: str) -> Dict[str, float]:
    """DEPRECATED — kept for backward compatibility only. Returns prices unchanged.

    Historically, when variant_style == 'lunch_based' this rewrote EVERY paper
    'Small' key to 'Lunch' across the whole restaurant. That was wrong: a single
    ChAm menu mixes axes — Soup / White Rice use a genuine Small/Large (cup/bowl,
    Pt/Qt) split, while mains use the Lunch column. One restaurant-wide style
    cannot represent both, so the blind remap silently dropped legitimate Soup
    'Small' prices (the remapped 'Lunch' value had no slot on a Soup row).

    The remap is now SECTION-AWARE and performed per system row inside
    map_prices_to_2a_row(): a paper 'Small' is routed to 'Lunch' ONLY when the
    matched system row actually exposes a 'Lunch' slot and has no 'Small' slot.
    Rows that genuinely use Small/Large keep their Small price. This function is
    left as a pass-through so any external callers don't break.
    """
    return prices


def _route_small_to_lunch_for_row(ocr_prices: Dict[str, float],
                                  row_2a_prices: Dict[str, Optional[float]],
                                  variant_style: str) -> Dict[str, float]:
    """Section-aware Small→Lunch routing, decided per matched system row.

    Rationale (replaces the old global remap_ocr_prices):
      - Only relevant for lunch_based restaurants (the historical case where a
        paper 'first column' price is really a Lunch price).
      - Route a paper 'Small' to 'Lunch' ONLY when THIS system row has a 'Lunch'
        slot populated and does NOT have a 'Small' slot. That confines the remap
        to mains (Lunch column) and leaves Soup / White Rice (genuine Small/Large)
        untouched — fixing the silent-drop bug.
    """
    if variant_style != 'lunch_based':
        return ocr_prices
    has = {v for v, p in row_2a_prices.items() if p is not None}
    if 'Lunch' in has and 'Small' not in has and 'Small' in ocr_prices:
        rerouted = dict(ocr_prices)
        rerouted['Lunch'] = rerouted.pop('Small')
        return rerouted
    return ocr_prices

