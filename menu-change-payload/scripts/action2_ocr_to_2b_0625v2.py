def validate_json(data: dict) -> List[str]:
    warnings = []
    if 'restaurant' not in data:
        warnings.append("Missing 'restaurant' object")
    sections = data.get('sections', [])
    if not sections:
        warnings.append("No menu sections found")
    
    for sec in sections:
        sec_name = sec.get('menu_section', '?')
        prices_by_var = defaultdict(list)
        for item in sec.get('items', []):
            for v, p in item.get('prices', {}).items():
                prices_by_var[v].append((item.get('name', '?'), p))
        for var, plist in prices_by_var.items():
            if len(plist) < 3: continue
            vals = sorted([p for _, p in plist])
            if len(vals) >= 2 and vals[0] > 0 and vals[1] > 0 and vals[0] < vals[1] * 0.65:
                for n, p in plist:
                    if p == vals[0]:
                        warnings.append(f"PRICE OUTLIER: '{n}' in {sec_name} {var}=${p:.2f} vs next ${vals[1]:.2f}")
    return warnings


