            if _g('Dish Name') and _g('Variant'):
                out[(_g('Dish Name'), _g('Variant'))] = {
                    'source': _g('Source'), 'by_itself': _g('By Itself Rule'),
                    'evidence': _g('Evidence'), 'modifier_group': _g('Modifier Group')}
