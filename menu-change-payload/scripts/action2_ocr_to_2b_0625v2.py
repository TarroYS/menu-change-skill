    if different:
        print(f"\n  Name resolutions ({len(different)} different):")
        for m in different[:20]:
            print(f"    \"{m['menu']}\" → \"{m['system']}\" ({m['method']})")
        if len(different) > 20:
            print(f"    ... +{len(different)-20} more")

    if result.get('flagged_items'):
        print(f"\n  ⚠ Flagged code matches (P4 — verify these):")
        for item in result['flagged_items']:
            print(f"    Code {item['code']}: \"{item['clean_name']}\" → \"{item['system_name']}\"")

    if result['unmatched_items']:
        print(f"\n  Unmatched (P1):")
        for item in result['unmatched_items'][:10]:
            c_tag = f"[{item['code']}] " if item.get('code') else ""
            print(f"    {c_tag}[{item['section']}] {item['name']}")
        if len(result['unmatched_items']) > 10:
            print(f"    ... +{len(result['unmatched_items'])-10} more")

    if result['warnings']:
        print(f"\n  Warnings ({len(result['warnings'])}):")
        for w in result['warnings'][:5]:
            print(f"    {w}")

    print(f"\n  Output: {output_path}")
    print(f"{'='*50}")
    print("Done.")


