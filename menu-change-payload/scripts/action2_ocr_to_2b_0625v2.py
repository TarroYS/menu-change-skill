# Words that don't help distinguish dishes — shared across many items
_STOP_WORDS = {'with', 'and', 'or', 'in', 'the', 'style', 'on', 'a', 'of', 'for'}
_PROTEIN_WORDS = {'chicken', 'beef', 'pork', 'shrimp', 'vegetable', 'vegetables',
                  'tofu', 'seafood', 'lobster', 'scallop', 'house', 'special',
                  'fish', 'crab', 'squid', 'mixed'}
_COOKING_WORDS = {'fried', 'steamed', 'steam', 'roast', 'roasted', 'sauteed',
                  'grilled', 'baked', 'crispy', 'deep', 'stir', 'bbq', 'barbecue',
                  'boneless', 'fresh', 'white', 'meat'}

def _get_distinguishing_words(name: str) -> set:
    """Extract the words that make a dish name unique (not proteins, cooking methods, or stop words)."""
    normalized = _normalize(name).lower()
    words = set(normalized.split())
    # Remove non-distinguishing words
    words -= _STOP_WORDS
    words -= _PROTEIN_WORDS
    words -= _COOKING_WORDS
    # Also add singular/plural variants for matching
    expanded = set()
    for w in words:
        expanded.add(w)
        if w.endswith('s') and len(w) > 3:
            expanded.add(w[:-1])
        elif not w.endswith('s') and len(w) > 3:
            expanded.add(w + 's')
    return expanded

def _is_code_match_plausible(ocr_name: str, sys_name: str) -> bool:
    """Check if a code-matched pair has plausible name similarity.
    Returns True if at least 1 distinguishing word overlaps."""
    ocr_words = _get_distinguishing_words(ocr_name)
    sys_words = _get_distinguishing_words(sys_name)
    
    # If BOTH sides have zero distinguishing words (e.g., "Fried Chicken" vs "Roast Chicken"),
    # that's fine — they're both simple protein dishes, code is reliable
    if not ocr_words and not sys_words:
        return True
    
    # If one side has distinguishing words and the other doesn't, flag it
    if not ocr_words or not sys_words:
        return len(ocr_words) == 0 and len(sys_words) == 0
    
    # Check overlap
    overlap = ocr_words & sys_words
    return len(overlap) > 0



def _numeric_prices(node, path='', out=None):
    """Make every price in the OCR JSON a number, in place: "$9.59" / "9.59" →
    9.59 (a model sometimes writes prices as text); anything else ("MP",
    "market") → null, listed in the returned messages — never a crash, never
    silently read as a price. Keys: prices / side_prices (dict or list),
    price, default_price."""
    out = [] if out is None else out

    def num(v, where):
        if v is None or isinstance(v, bool):
            return None
        if isinstance(v, (int, float)):
            return float(v)
        s = str(v).strip().replace('$', '').replace(',', '')
        try:
            return float(s) if s else None
        except ValueError:
            out.append(f"NOT A PRICE in the OCR JSON: {where} = {v!r} — not read")
            return None

    if isinstance(node, dict):
        name = node.get('name') or node.get('menu_section') or path
        for k, v in list(node.items()):
            if k in ('prices', 'side_prices') and isinstance(v, dict):
                node[k] = {kk: num(vv, f"{name} {k}[{kk}]") for kk, vv in v.items()}
            elif k in ('prices', 'side_prices') and isinstance(v, list):
                node[k] = [num(vv, f"{name} {k}[{i}]") for i, vv in enumerate(v)]
            elif k in ('price', 'default_price') and not isinstance(v, (dict, list)):
                node[k] = num(v, f"{name} {k}")
            elif isinstance(v, (dict, list)):
                _numeric_prices(v, f"{path}/{k}", out)
    elif isinstance(node, list):
        for i, v in enumerate(node):
            _numeric_prices(v, f"{path}[{i}]", out)
    return out


def build_2b(ocr_path: str, path_2a: str, dict_path: str = None, output_path: str = None) -> dict:
    with open(ocr_path, 'r', encoding='utf-8') as f:
        ocr = json.load(f)

    not_prices = _numeric_prices(ocr)
    warnings = validate_json(ocr) + not_prices
    p_headers, price_rows, m_headers, mod_rows = read_2a(path_2a)
    absolute_cells = read_absolute_cells(path_2a)
    variant_style = detect_variant_style(p_headers, price_rows)

    equiv = {}
    if dict_path:
        try:
            equiv = _load_wonders_dict(dict_path)
        except Exception as e:
            print(f"  WARNING: Could not load dictionary: {e}")

    # Load Dish Codes natively from the excel_2a workbook
    code_index = _load_dish_codes_from_workbook(path_2a)

    name_col = p_headers.index('Dish Name:Primary') if 'Dish Name:Primary' in p_headers else 1
    sys_names = []
    for r in price_rows[1:]:
        if len(r) > name_col and r[name_col]:
            n = str(r[name_col]).strip()
            if n and n not in sys_names:
                sys_names.append(n)

    ocr_index = defaultdict(dict)
    # every printed price per dish and paper size — ocr_index keeps only the
    # last one; two different prices for one size are asked (P-PRICE), never picked
    printed_all = defaultdict(lambda: defaultdict(list))   # dish (lower) → paper size → [(price, section, name)]

    def _record(sys_name, prices, section, printed_name):
        for v, p in prices.items():
            ocr_index[sys_name.lower()][v] = p
            printed_all[sys_name.lower()][v].append((p, section, printed_name))

    match_log = []
    unmatched = []
    flagged_code_matches = []  # P4: code matched but name similarity too low
    inferred_routings = []  # P-COLUMN: paper variant blank in system, routed to the one populated column
    unplaced_prices = []    # P-SIZE: a printed price for a size the system dish does not have

    def _is_drink(name: str) -> bool:
        n = name.lower()
        for pat in DRINK_PATTERNS:
            if re.search(pat, n):
                return True
        return False

    def _normalize_protein(part: str, dish_base: str) -> str:
        p_lower = part.strip().lower()
        protein_map = {
            'vegetable': 'Vegetable', 'vegetables': 'Vegetable',
            'veg': 'Vegetable', 'vegs': 'Vegetable',
            'pork': 'Pork', 'fresh pork': 'Pork', 'roast pork': 'Pork',
            'chicken': 'Chicken', 'beef': 'Beef', 'shrimp': 'Shrimp',
            'house special': 'House Special',
        }
        protein = protein_map.get(p_lower, part.strip())
        return f'{dish_base} {protein}' if dish_base else protein

    def _expand_parenthetical(name: str, prices: dict) -> List[Tuple[str, dict]]:
        n = name.strip()
        suffix_match = re.match(r'^(.+?)\s*\((.+)\)\s*$', n)
        if suffix_match:
            base = suffix_match.group(1).strip()
            inner = suffix_match.group(2).strip()
            if ',' in inner or ' or ' in inner.lower():
                parts = re.split(r',\s*|\s+or\s+', inner)
                parts = [p.strip() for p in parts if p.strip()]
                if len(parts) >= 2:
                    return [(_normalize_protein(p, base), prices) for p in parts]

        prefix_match = re.match(r'^\((.+?)\)\s+(.+)$', n)
        if prefix_match:
            inner = prefix_match.group(1).strip()
            base = prefix_match.group(2).strip()
            if ',' in inner or ' or ' in inner.lower():
                parts = re.split(r',\s*|\s+or\s+', inner)
                parts = [p.strip() for p in parts if p.strip()]
                if len(parts) >= 2:
                    result = []
                    for p in parts:
                        p_lower = p.strip().lower()
                        protein_map = {
                            'vegetable': 'Vegetable', 'vegetables': 'Vegetable',
                            'pork': 'Pork', 'fresh pork': 'Pork', 'roast pork': 'Pork',
                            'chicken': 'Chicken', 'beef': 'Beef', 'shrimp': 'Shrimp',
                        }
                        protein = protein_map.get(p_lower, p.strip())
                        result.append((f'{protein} {base}', prices))
                    return result

        for dish_base in ['Moo Shu', 'Egg Foo Young']:
            base_match = re.match(rf'^({re.escape(dish_base)})\s+(.+)$', n, re.IGNORECASE)
            if base_match:
                base = base_match.group(1).strip()
                rest = base_match.group(2).strip()
                if ',' in rest or ' or ' in rest.lower():
                    parts = re.split(r',\s*|\s+or\s+', rest)
                    parts = [p.strip() for p in parts if p.strip()]
                    if len(parts) >= 2:
                        return [(_normalize_protein(p, base), prices) for p in parts]
        return [(n, prices)]

