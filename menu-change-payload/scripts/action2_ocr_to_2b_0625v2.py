def _clean_ocr_noise(text: str) -> str:
    if not text: return ""
    t = re.sub(r'[^\x00-\x7F]+', ' ', text)
    t = re.sub(r'([a-zA-Z])(\d+\.\d{2})', r'\1 \2', t)
    t = re.sub(r'^([A-Za-z]?\d+[a-zA-Z]?)([A-Za-z])', r'\1 \2', t)
    return re.sub(r'\s+', ' ', t).strip()

def _extract_prefix_code(name: str) -> Tuple[Optional[str], str]:
    match = re.match(r'^([A-Za-z]?\d+[a-zA-Z]?)[.)\-\s]+(.*)', name)
    if match:
        return match.group(1).strip(), match.group(2).strip()
    return None, name

def _extract_quantity(name: str) -> Tuple[Optional[str], str]:
    match = re.search(r'\s*\(\s*(\d+)\s*\)\s*$', name)
    if match:
        qty = match.group(1)
        clean_name = re.sub(r'\s*\(\s*\d+\s*\)\s*$', '', name).strip()
        return qty, clean_name
    return None, name


